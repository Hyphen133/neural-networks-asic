if __name__ == "__main__":
    ap = argparse.ArgumentParser()
    ap.add_argument("--tag", default="default")
    ap.add_argument("--placeholder", default=None,
                    help="nbank,nslot,frame_log2,feat_w -- emit a zero-weight "
                         "header so the RTL compiles before training")
    ap.add_argument("--vectors", action="store_true")
    ap.add_argument("--vector-clips", type=int, default=6)
    a = ap.parse_args()

    if a.placeholder:
        nb, ns, fl, fw = (int(v) for v in a.placeholder.split(","))
        cfg = KWSConfig(nbank=nb, nslot=ns, frame_log2=fl, feat_w=fw)
        w = np.zeros((cfg.nclass, cfg.nslot, cfg.nband), dtype=np.int64)
        b = np.zeros(cfg.nclass, dtype=np.int64)
        p = write_header(w, b, cfg,
                         note="PLACEHOLDER: all weights zero, no model trained.")
        print(f"wrote {p} (placeholder)")
    else:
        w, bias, cfg, blob = load_weights(a.tag)
        acc = blob.get("test_acc")
        note = (f"Speech Commands v0.02 test set: clip accuracy "
                f"{acc*100:.2f}%" if acc else "")
        p = write_header(w, bias, cfg, note=note)
        print(f"wrote {p}")
        print(bank_report(cfg.nbank))
        print(f"\n  weights: {w.size} int4 in [{w.min()}, {w.max()}]")
        print(f"  biases : {bias.tolist()}")
        if a.vectors:
            vp, shape = write_vectors(cfg, n=a.vector_clips)
            print(f"  vectors: {vp} {shape}")
